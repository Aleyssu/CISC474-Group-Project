env = gym.make("standard", render_mode="human", predefined_map_list=tim_maps, activate_game_status=True)
num_episodes = 10
for i in range(num_episodes):
    done = False
    obs, _ = env.reset()
    while not done:
        action, _ = model.predict(obs, deterministic=True)
        obs, reward, done, truncated, info = env.step(action)
        print(f"Action taken: {action}, Reward received: {reward}")

        # Sleep may be used to allow each step to be visualized. Value can be changed
        print(obs)
        time.sleep(0.04)
    if done:
        time.sleep(2)
